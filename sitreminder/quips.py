# 兼容旧引用（tests / 遗留 Tk 版）：QUIPS 即「默认」风格那一组
QUIPS = QUIPS_BY_STYLE[DEFAULT_STYLE]

# 「随机」的池子 = 全部风格合并
_ALL_POOL = [q for _quips in QUIPS_BY_STYLE.values() for q in _quips]

_last: str = None


def pick_quip(style: str = DEFAULT_STYLE) -> str:
    """按风格随机取一条，且尽量不与上一条重复（连着两次一样会很出戏）。

    style 取 STYLES 里的值；「随机」用全量池子；未知/缺失风格退回「默认」。
    """
    global _last
    if style == MIX_STYLE:
        pool = _ALL_POOL
    else:
        pool = QUIPS_BY_STYLE.get(style, QUIPS)
    if not pool:
        return "该起来活动一下啦～"
    if len(pool) == 1:
        return pool[0]

    idx = random.randrange(len(pool))
    if pool[idx] == _last:
        # 换一条不同的：在剩余 len-1 条里偏移一个随机量
        idx = (idx + 1 + random.randrange(len(pool) - 1)) % len(pool)
    _last = pool[idx]
    return pool[idx]
